ALTER TABLE our_adventures.users
  ALTER COLUMN google_sub DROP NOT NULL;

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1
    FROM pg_constraint
    WHERE conname = 'users_google_sub_key'
      AND connamespace = 'our_adventures'::regnamespace
  ) THEN
    ALTER TABLE our_adventures.users
      ADD CONSTRAINT users_google_sub_key UNIQUE (google_sub);
  END IF;
END
$$;
